#!/usr/bin/env python3
"""
508 Media Co. intake page -> Squarespace (508mediaco.com/intake, Not Linked).

  index.html                                 source + standalone preview (edit this)
  squarespace-page-header-injection.html     paste into Page Settings > Advanced > Page Header Code Injection

Same pattern as hds-fleet: the site-wide footer injection draws the homepage (#mc508) on every page, so this
hides it and mounts the intake from a <template>. CSS is re-scoped from :root/body/bare selectors to #in508 so
Squarespace's own form styles can't leak in. Submits to the existing Google Form (formResponse).
"""
import pathlib, re

HERE = pathlib.Path(__file__).parent
src = (HERE / "index.html").read_text()
css = src[src.index("<style>") + 7:src.index("</style>")]
body = src[src.index('<div class="wrap">'):src.index("<script>")].strip()
script = src[src.index("<script>") + 8:src.index("</script>")].strip()
links = "\n".join(re.findall(r'<link [^>]+>', src))

def scope(sel):
    sel = sel.strip()
    if sel in (":root", "body"): return "#in508"
    if sel == "html": return "html"
    if sel.startswith("::selection"): return "#in508 ::selection"
    if sel.startswith("*"): return "#in508, #in508 *" if sel == "*" else "#in508 " + sel
    return "#in508 " + sel

def scope_block(text):
    out, i = [], 0
    for m in re.finditer(r'([^{}]+)\{([^{}]*)\}', text):
        sels = m.group(1)
        if sels.strip().startswith("/*"):  # leading comment
            c = sels[:sels.index("*/") + 2]; sels = sels[sels.index("*/") + 2:]; out.append(c)
        out.append(",".join(scope(s) for s in sels.split(",")) + "{" + m.group(2) + "}")
    return "\n".join(out)

def scope_css(css):
    res, pos = [], 0
    for m in re.finditer(r'@media[^{]+\{((?:[^{}]*\{[^{}]*\})*)\s*\}', css):
        res.append(scope_block(css[pos:m.start()]))
        head = css[m.start():css.index("{", m.start())]
        res.append(head + "{" + scope_block(m.group(1)) + "}")
        pos = m.end()
    res.append(scope_block(css[pos:]))
    return "\n".join(r for r in res if r.strip())

scoped = scope_css(css)
# the script looks things up by id/class, all inside #in508; '.prog' query stays unique
inj = f"""<!-- 508 Media Co. | client intake ("Let's plan your video"). Generated by intake/build.py; edit index.html. -->
<meta name="robots" content="noindex,nofollow">
{links}
<style>
{scoped}
#mc508{{display:none!important}} html,body{{background:#06070A!important}}
</style>
<template id="in508tpl">
<div id="in508">
{body}
</div>
</template>
<script>
document.addEventListener('DOMContentLoaded', function(){{
  var t = document.getElementById('in508tpl');
  if (!t || document.getElementById('in508')) return;
  document.body.appendChild(t.content.cloneNode(true));
  {script}
}});
</script>
"""
(HERE / "squarespace-page-header-injection.html").write_text(inj)
print("injection", len(inj), "bytes;", scoped.count("#in508"), "scoped selectors")

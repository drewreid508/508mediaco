#!/usr/bin/env python3
"""
508 Media Co. "Let's Plan Your Video" page → Squarespace (508mediaco.com/plan, Not Linked) + local preview.

  page.html                                  source (edit this)
  squarespace-page-header-injection.html     paste into Page Settings → Advanced → Page Header Code Injection
  index.html                                 local preview / Artifact

Same pattern as hq-southpark and hds-fleet: the site-wide 508 footer injection draws the homepage (#mc508)
on every page, so the injection hides it and mounts #plan508 from a <template> once the DOM is ready.
"""
import pathlib

HERE = pathlib.Path(__file__).parent
CFG = {
    # live intake form, built Oct 8 by 508mediaco-intake-form/CreateIntakeForm.gs; answers → "508 Media Co. Intake Responses"
    "FORM_URL": "https://docs.google.com/forms/d/e/1FAIpQLSfROgQwJWUtFt8sdJosInhRF0wWPxV2anHH8EQl7AM-93WHKg/viewform",
}

src = (HERE / "page.html").read_text()
for k, v in CFG.items():
    src = src.replace("{{" + k + "}}", v)
assert "{{" not in src, "unfilled token"
head = src[src.index('<link rel="preconnect"'):src.index("</style>") + len("</style>")]
body = src[src.index('<div id="plan508">'):src.index("<script>")].strip()
script = src[src.index("<script>") + len("<script>"):src.index("</script>")].strip()

injection = f"""<!-- 508 Media Co. | Let's Plan Your Video intake page. Generated by plan/build.py; edit page.html. -->
<meta name="robots" content="noindex,nofollow">
<meta property="og:image" content="https://drewreid508.github.io/508mediaco/media-v2/og-image.jpg">
{head}
<style>#mc508{{display:none!important}} html,body{{background:#06070A!important}}</style>
<template id="plan508tpl">
{body}
</template>
<script>
document.addEventListener('DOMContentLoaded', function(){{
  var t = document.getElementById('plan508tpl');
  if (!t || document.getElementById('plan508')) return;
  document.body.appendChild(t.content.cloneNode(true));
  {script}
}});
</script>
"""
(HERE / "squarespace-page-header-injection.html").write_text(injection)
(HERE / "index.html").write_text(f"""<title>Plan Your Video</title>
{head}<style>:root{{color-scheme:dark;background:#06070A}} html,body{{margin:0;background:#06070A}}</style>
{body}
<script>{script}</script>
""")
print("injection", len(injection), "bytes")
